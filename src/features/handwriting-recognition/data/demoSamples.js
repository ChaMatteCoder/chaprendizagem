function createVectorFromPattern(pattern, variant = 0) {
  const vector = Array(784).fill(0);
  const scale = 3;
  const offsetX = 6 + (variant % 3) - 1;
  const offsetY = 4 + Math.floor(variant / 3) - 1;

  pattern.forEach((row, y) => {
    row.split('').forEach((cell, x) => {
      if (cell !== '1') return;

      for (let dy = 0; dy < scale; dy += 1) {
        for (let dx = 0; dx < scale; dx += 1) {
          const px = offsetX + x * scale + dx;
          const py = offsetY + y * scale + dy;
          if (px >= 0 && px < 28 && py >= 0 && py < 28) {
            const softness = dx === 1 && dy === 1 ? 1 : 0.72;
            vector[py * 28 + px] = Math.max(vector[py * 28 + px], softness);
          }
        }
      }
    });
  });

  return vector;
}

export function createDemoDataset(modeConfig, variantsPerClass = 3) {
  const source =
    modeConfig.id === 'letters'
      ? letterStrokes
      : modeConfig.id === 'all'
        ? { ...digitStrokes, ...letterStrokes }
        : digitStrokes;

  return modeConfig.classes.flatMap((label) =>
    Array.from({ length: variantsPerClass }, (_, variant) => {
      const pattern = source[label];

      if (!pattern) {
        throw new Error(`Amostra didática não encontrada para a classe "${label}" no modo ${modeConfig.id}.`);
      }

      return {
        label,
        input: createVectorFromPattern(pattern, variant),
      };
    }),
  );
}
